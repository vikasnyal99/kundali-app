"""Build app/data/places.tsv.gz from GeoNames (CC BY 4.0, https://www.geonames.org/).

Usage: python -I server/scripts/build_places.py <download_dir>
Downloads cities15000.zip and admin1CodesASCII.txt into <download_dir> (treated as data only),
then writes name, region, country, latitude, longitude, IANA timezone, population, Hindi aliases.
"""
import csv
import gzip
import io
import sys
import urllib.request
import zipfile
from pathlib import Path

BASE='https://download.geonames.org/export/dump/'
OUT=Path(__file__).resolve().parents[1]/'app'/'data'/'places.tsv.gz'
csv.field_size_limit(10**7)

def fetch(directory,name):
    path=directory/name
    if not path.exists(): urllib.request.urlretrieve(BASE+name,path)
    return path

def devanagari(names):
    """All Devanagari aliases, '|'-separated: used only as Hindi search keys."""
    return '|'.join(dict.fromkeys(n.strip() for n in names.split(',') if any('ऀ'<=ch<='ॿ' for ch in n)))

def main(directory):
    directory.mkdir(parents=True,exist_ok=True)
    regions={}
    for row in csv.reader(fetch(directory,'admin1CodesASCII.txt').read_text(encoding='utf-8').splitlines(),delimiter='\t'):
        regions[row[0]]=row[1]
    with zipfile.ZipFile(fetch(directory,'cities15000.zip')) as z:
        text=io.TextIOWrapper(z.open('cities15000.txt'),encoding='utf-8')
        rows=[]
        for r in csv.reader(text,delimiter='\t',quoting=csv.QUOTE_NONE):
            name,lat,lon,country,admin1,population,tz=r[1],float(r[4]),float(r[5]),r[8],r[10],int(r[14] or 0),r[17]
            if not tz: continue
            hindi=devanagari(r[3]) if country in ('IN','NP') else ''
            rows.append((name,regions.get(f'{country}.{admin1}',''),country,f'{lat:.4f}',f'{lon:.4f}',tz,str(population),hindi))
    rows.sort(key=lambda r:-int(r[6]))
    OUT.parent.mkdir(parents=True,exist_ok=True)
    with gzip.open(OUT,'wt',encoding='utf-8',compresslevel=9) as f:
        f.write('# GeoNames cities15000 (CC BY 4.0, https://www.geonames.org/). Generated by scripts/build_places.py\n')
        for r in rows: f.write('\t'.join(c.replace('\t',' ') for c in r)+'\n')
    print(f'{len(rows)} places -> {OUT} ({OUT.stat().st_size//1024} KiB)')

if __name__=='__main__': main(Path(sys.argv[1]))

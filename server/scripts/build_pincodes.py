"""Build app/data/pincodes.tsv.gz from GeoNames India postal codes (CC BY 4.0, https://www.geonames.org/).

Usage: python -I server/scripts/build_pincodes.py <download_dir>
Downloads export/zip/IN.zip into <download_dir> (treated as data only), then writes one row per post office:
pincode, office (place) name, district, state, latitude, longitude. All of India uses Asia/Kolkata.
"""
import csv
import gzip
import io
import sys
import urllib.request
import zipfile
from pathlib import Path

URL='https://download.geonames.org/export/zip/IN.zip'
OUT=Path(__file__).resolve().parents[1]/'app'/'data'/'pincodes.tsv.gz'

def main(directory):
    directory.mkdir(parents=True,exist_ok=True)
    path=directory/'IN.zip'
    if not path.exists(): urllib.request.urlretrieve(URL,path)
    rows=set()
    with zipfile.ZipFile(path) as z:
        for r in csv.reader(io.TextIOWrapper(z.open('IN.txt'),encoding='utf-8'),delimiter='\t',quoting=csv.QUOTE_NONE):
            pincode,office,state,district,lat,lon=r[1],r[2].strip(),r[3].strip(),r[5].strip(),r[9],r[10]
            if len(pincode)!=6 or not pincode.isdigit() or not office or not lat or not lon: continue
            rows.add((pincode,office,district,state,f'{float(lat):.4f}',f'{float(lon):.4f}'))
    OUT.parent.mkdir(parents=True,exist_ok=True)
    with gzip.open(OUT,'wt',encoding='utf-8',compresslevel=9) as f:
        f.write('# GeoNames India postal codes (CC BY 4.0, https://www.geonames.org/). Generated by scripts/build_pincodes.py\n')
        for r in sorted(rows): f.write('\t'.join(c.replace('\t',' ') for c in r)+'\n')
    print(f'{len(rows)} post offices -> {OUT} ({OUT.stat().st_size//1024} KiB)')

if __name__=='__main__': main(Path(sys.argv[1]))
